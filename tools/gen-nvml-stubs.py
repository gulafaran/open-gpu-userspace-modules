#!/usr/bin/env python3
# Generates a weak stub for every symbol the closed libnvidia-ml exports
# (nvidia-ml/exports.txt): it returns NVML_ERROR_NOT_SUPPORTED (3). Real
# implementations are strong definitions and replace the stub at link time,
# so every export exists even before it is implemented; programs with full
# generated bindings (conky, LACT) resolve all symbols eagerly.
#
#   gen-nvml-stubs.py exports.txt out.c
import sys

names = [l.strip() for l in open(sys.argv[1]) if l.strip() and not l.startswith('#')]
with open(sys.argv[2], 'w') as out:
    out.write('/* Generated by tools/gen-nvml-stubs.py, do not edit. */\n\n')
    out.write('#define STUB(name) \\\n'
              '    __attribute__((weak, visibility("default"))) int name(void) { return 3; }\n\n')
    for n in names:
        out.write(f'STUB({n})\n')
